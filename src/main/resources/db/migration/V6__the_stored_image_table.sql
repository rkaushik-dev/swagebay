-- The image store's table: one row per file, against the radiograph it holds. File names are
-- unique across the whole store, and each radiograph's revisions count from zero.

CREATE TABLE stored_image (
    radiograph_id INTEGER NOT NULL,
    filename CHARACTER VARYING(80) NOT NULL,
    image_format CHARACTER VARYING(8) NOT NULL,
    purpose CHARACTER VARYING(10) NOT NULL,
    revision INTEGER NOT NULL,
    bit_depth INTEGER NOT NULL,
    width INTEGER NOT NULL,
    height INTEGER NOT NULL,
    byte_size BIGINT NOT NULL,
    digest CHARACTER VARYING(64) NOT NULL,
    captured_at TIMESTAMP(6) NOT NULL,
    ingested_at TIMESTAMP(6) NOT NULL,
    ingested_by CHARACTER VARYING(20) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_stored_image_an_empty_file_is_not_an_image CHECK (byte_size > 0),
    CONSTRAINT ck_stored_image_a_digest_is_sixty_four_characters CHECK (length(digest) = 64),
    CONSTRAINT ck_stored_image_revisions_count_from_zero CHECK (revision >= 0),
    CONSTRAINT ck_stored_image_an_image_has_both_dimensions CHECK (width > 0 AND height > 0),
    CONSTRAINT fk_stored_image_radiograph_id_radiograph FOREIGN KEY (radiograph_id) REFERENCES radiograph (id),
    CONSTRAINT pk_stored_image PRIMARY KEY (id),
    CONSTRAINT uq_stored_image_filename UNIQUE (filename),
    CONSTRAINT uq_stored_image_radiograph_id UNIQUE (radiograph_id, revision)
);
CREATE INDEX ix_stored_image_radiograph_id ON stored_image (radiograph_id);
