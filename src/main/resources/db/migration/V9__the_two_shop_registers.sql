-- The two shop registers: what each device was used for, day by day and site by site, and every
-- source exchange made on a device.

CREATE TABLE device_use (
    device_serial CHARACTER VARYING(40) NOT NULL,
    source_serial CHARACTER VARYING(40) NOT NULL,
    used_on DATE NOT NULL,
    site CHARACTER VARYING(120) NOT NULL,
    radiographers CHARACTER VARYING NOT NULL,
    exposures INTEGER NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_device_use_exposures_do_not_go_backwards CHECK (exposures >= 0),
    CONSTRAINT ck_device_use_a_use_names_somebody CHECK (length(radiographers) > 0),
    CONSTRAINT ck_device_use_a_use_names_where CHECK (length(site) > 0),
    CONSTRAINT pk_device_use PRIMARY KEY (id),
    CONSTRAINT uq_device_use_device_serial UNIQUE (device_serial, used_on, site)
);
CREATE INDEX ix_device_use_day ON device_use (used_on);
CREATE INDEX ix_device_use_device ON device_use (device_serial, used_on);
CREATE INDEX ix_device_use_source ON device_use (source_serial, used_on);

CREATE TABLE exchange (
    device_serial CHARACTER VARYING(40) NOT NULL,
    removed_serial CHARACTER VARYING(40),
    installed_serial CHARACTER VARYING(40),
    performed_on DATE NOT NULL,
    performed_by CHARACTER VARYING(20) NOT NULL,
    shipment CHARACTER VARYING(60) NOT NULL,
    notes CHARACTER VARYING(400) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_exchange_an_exchange_names_the_device CHECK (length(device_serial) > 0),
    CONSTRAINT ck_exchange_an_exchange_is_signed CHECK (length(performed_by) > 0),
    CONSTRAINT ck_exchange_an_exchange_names_the_shipment CHECK (length(shipment) > 0),
    CONSTRAINT ck_exchange_an_exchange_moved_something CHECK (removed_serial IS NOT NULL OR installed_serial IS NOT NULL),
    CONSTRAINT ck_exchange_an_exchange_is_not_the_same_source_twice CHECK (removed_serial IS NULL OR removed_serial <> installed_serial),
    CONSTRAINT pk_exchange PRIMARY KEY (id)
);
CREATE INDEX ix_exchange_device ON exchange (device_serial, performed_on);
CREATE INDEX ix_exchange_shipment ON exchange (shipment);
