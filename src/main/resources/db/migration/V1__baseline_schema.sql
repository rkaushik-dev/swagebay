-- The baseline schema: counters, the reference tables, sources and their devices, surveys and
-- dose, and the work tree of jobs, welds, radiographs and indications.
--
-- Quantities are whole base units in a BIGINT (micrometres, becquerels, nanosieverts), decimals
-- are their exact text, and every constraint carries the name the naming convention gives it.

CREATE TABLE counter (
    name CHARACTER VARYING(40) NOT NULL,
    scope CHARACTER VARYING(40) NOT NULL,
    next_value INTEGER NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_counter_counter_starts_at_one CHECK (next_value >= 1),
    CONSTRAINT pk_counter PRIMARY KEY (id),
    CONSTRAINT uq_counter_name UNIQUE (name, scope)
);

CREATE TABLE device (
    serial CHARACTER VARYING(40) NOT NULL,
    model_key CHARACTER VARYING(20) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT pk_device PRIMARY KEY (id),
    CONSTRAINT uq_device_serial UNIQUE (serial)
);

CREATE TABLE dose_entry (
    badge CHARACTER VARYING(20) NOT NULL,
    year INTEGER NOT NULL,
    taken BIGINT NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    source_of_entry CHARACTER VARYING(40) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_dose_entry_dose_not_negative CHECK (taken >= 0),
    CONSTRAINT pk_dose_entry PRIMARY KEY (id)
);

CREATE TABLE dosimeter (
    serial CHARACTER VARYING(40) NOT NULL,
    kind CHARACTER VARYING(30) NOT NULL,
    badge CHARACTER VARYING(20) NOT NULL,
    worker_class CHARACTER VARYING(30) NOT NULL,
    calibration_due DATE,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_dosimeter_kind_known CHECK (kind IN ('badge', 'direct reading', 'alarming ratemeter')),
    CONSTRAINT pk_dosimeter PRIMARY KEY (id),
    CONSTRAINT uq_dosimeter_serial UNIQUE (serial)
);

CREATE TABLE film (
    key CHARACTER VARYING(20) NOT NULL,
    revision INTEGER NOT NULL,
    name CHARACTER VARYING(80) NOT NULL,
    manufacturer CHARACTER VARYING(80) NOT NULL,
    film_class CHARACTER VARYING(10) NOT NULL,
    speed_index CHARACTER VARYING NOT NULL,
    granularity CHARACTER VARYING NOT NULL,
    effective_on DATE NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_film_speed_positive CHECK (speed_index > 0),
    CONSTRAINT pk_film PRIMARY KEY (id),
    CONSTRAINT uq_film_key UNIQUE (key, revision)
);

CREATE TABLE isotope (
    key CHARACTER VARYING(20) NOT NULL,
    revision INTEGER NOT NULL,
    symbol CHARACTER VARYING(20) NOT NULL,
    half_life_days CHARACTER VARYING NOT NULL,
    gamma_constant CHARACTER VARYING NOT NULL,
    energy_kev_low INTEGER NOT NULL,
    energy_kev_high INTEGER NOT NULL,
    steel_min BIGINT NOT NULL,
    steel_max BIGINT NOT NULL,
    effective_on DATE NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_isotope_energy_band_ordered CHECK (energy_kev_low <= energy_kev_high),
    CONSTRAINT ck_isotope_half_life_positive CHECK (half_life_days > 0),
    CONSTRAINT pk_isotope PRIMARY KEY (id),
    CONSTRAINT uq_isotope_key UNIQUE (key, revision)
);

CREATE TABLE job (
    year INTEGER NOT NULL,
    serial INTEGER NOT NULL,
    client CHARACTER VARYING(120) NOT NULL,
    site CHARACTER VARYING(120) NOT NULL,
    acceptance_code CHARACTER VARYING(40) NOT NULL,
    procedure_number CHARACTER VARYING(40) NOT NULL,
    opened_on DATE NOT NULL,
    closed_on DATE,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_job_serial_in_range CHECK (serial BETWEEN 1 AND 9999),
    CONSTRAINT ck_job_year_two_digits CHECK (year BETWEEN 0 AND 99),
    CONSTRAINT pk_job PRIMARY KEY (id),
    CONSTRAINT uq_job_year UNIQUE (year, serial)
);

CREATE TABLE material (
    key CHARACTER VARYING(40) NOT NULL,
    revision INTEGER NOT NULL,
    name CHARACTER VARYING(80) NOT NULL,
    density_kg_m3 INTEGER NOT NULL,
    ferrous BOOLEAN NOT NULL,
    effective_on DATE NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_material_density_positive CHECK (density_kg_m3 > 0),
    CONSTRAINT ck_material_revision_not_negative CHECK (revision >= 0),
    CONSTRAINT pk_material PRIMARY KEY (id),
    CONSTRAINT uq_material_key UNIQUE (key, revision)
);

CREATE TABLE source (
    serial CHARACTER VARYING(40) NOT NULL,
    isotope_key CHARACTER VARYING(20) NOT NULL,
    assay_activity BIGINT NOT NULL,
    assay_at TIMESTAMP(6) NOT NULL,
    manufacturer CHARACTER VARYING(80) NOT NULL,
    model CHARACTER VARYING(80) NOT NULL,
    active_diameter BIGINT NOT NULL,
    active_length BIGINT NOT NULL,
    state CHARACTER VARYING(30) NOT NULL,
    working_floor BIGINT NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_source_pellet_diameter_positive CHECK (active_diameter > 0),
    CONSTRAINT ck_source_pellet_length_positive CHECK (active_length > 0),
    CONSTRAINT ck_source_assay_positive CHECK (assay_activity > 0),
    CONSTRAINT pk_source PRIMARY KEY (id),
    CONSTRAINT uq_source_serial UNIQUE (serial)
);

CREATE TABLE survey (
    radiograph_number CHARACTER VARYING(40),
    stage CHARACTER VARYING(10) NOT NULL,
    performed_at TIMESTAMP(6) NOT NULL,
    performed_by CHARACTER VARYING(40) NOT NULL,
    instrument CHARACTER VARYING(80) NOT NULL,
    calibration_due TIMESTAMP(6) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_survey_stage_known CHECK (stage IN ('before', 'after')),
    CONSTRAINT pk_survey PRIMARY KEY (id)
);

CREATE TABLE leak_test (
    source_id INTEGER NOT NULL,
    performed_at TIMESTAMP(6) NOT NULL,
    becquerels_removed CHARACTER VARYING NOT NULL,
    technician CHARACTER VARYING(40) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_leak_test_removed_not_negative CHECK (becquerels_removed >= 0),
    CONSTRAINT fk_leak_test_source_id_source FOREIGN KEY (source_id) REFERENCES source (id),
    CONSTRAINT pk_leak_test PRIMARY KEY (id)
);

CREATE TABLE sighting (
    source_id INTEGER NOT NULL,
    seen_on DATE NOT NULL,
    seen_by CHARACTER VARYING(40) NOT NULL,
    location CHARACTER VARYING(120) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT fk_sighting_source_id_source FOREIGN KEY (source_id) REFERENCES source (id),
    CONSTRAINT pk_sighting PRIMARY KEY (id)
);

CREATE TABLE survey_point (
    survey_id INTEGER NOT NULL,
    label CHARACTER VARYING(80) NOT NULL,
    distance BIGINT NOT NULL,
    bearing_degrees INTEGER NOT NULL,
    reading BIGINT NOT NULL,
    at_device_surface BOOLEAN NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_survey_point_point_has_a_distance CHECK (distance > 0),
    CONSTRAINT fk_survey_point_survey_id_survey FOREIGN KEY (survey_id) REFERENCES survey (id),
    CONSTRAINT pk_survey_point PRIMARY KEY (id)
);

CREATE TABLE trip (
    source_id INTEGER NOT NULL,
    device_id INTEGER NOT NULL,
    crew_badge CHARACTER VARYING(20) NOT NULL,
    site CHARACTER VARYING(120) NOT NULL,
    went_out DATE NOT NULL,
    came_back DATE,
    exposures INTEGER NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_trip_return_after_departure CHECK (came_back IS NULL OR came_back >= went_out),
    CONSTRAINT ck_trip_exposures_not_negative CHECK (exposures >= 0),
    CONSTRAINT fk_trip_device_id_device FOREIGN KEY (device_id) REFERENCES device (id),
    CONSTRAINT fk_trip_source_id_source FOREIGN KEY (source_id) REFERENCES source (id),
    CONSTRAINT pk_trip PRIMARY KEY (id)
);

CREATE TABLE weld (
    job_id INTEGER NOT NULL,
    prefix CHARACTER VARYING(4) NOT NULL,
    number INTEGER NOT NULL,
    repair_round INTEGER NOT NULL,
    material_key CHARACTER VARYING(40) NOT NULL,
    outside_diameter BIGINT,
    wall BIGINT NOT NULL,
    reinforcement BIGINT NOT NULL,
    weld_length BIGINT NOT NULL,
    welder CHARACTER VARYING(40) NOT NULL,
    welded_on DATE NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_weld_repair_round_not_negative CHECK (repair_round >= 0),
    CONSTRAINT ck_weld_wall_positive CHECK (wall > 0),
    CONSTRAINT ck_weld_weld_length_positive CHECK (weld_length > 0),
    CONSTRAINT fk_weld_job_id_job FOREIGN KEY (job_id) REFERENCES job (id),
    CONSTRAINT pk_weld PRIMARY KEY (id),
    CONSTRAINT uq_weld_job_id UNIQUE (job_id, prefix, number, repair_round)
);

CREATE TABLE radiograph (
    weld_id INTEGER NOT NULL,
    number CHARACTER VARYING(40) NOT NULL,
    exposure_index INTEGER NOT NULL,
    exposed_at TIMESTAMP(6) NOT NULL,
    technique_reference CHARACTER VARYING(80) NOT NULL,
    medium CHARACTER VARYING(40) NOT NULL,
    admissible BOOLEAN NOT NULL,
    inadmissible_reason CHARACTER VARYING(400),
    density_through_indicator CHARACTER VARYING,
    normalised_snr CHARACTER VARYING,
    read_by CHARACTER VARYING(40),
    read_at TIMESTAMP(6),
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_radiograph_exposure_from_one CHECK (exposure_index >= 1),
    CONSTRAINT fk_radiograph_weld_id_weld FOREIGN KEY (weld_id) REFERENCES weld (id),
    CONSTRAINT pk_radiograph PRIMARY KEY (id),
    CONSTRAINT uq_radiograph_number UNIQUE (number),
    CONSTRAINT uq_radiograph_weld_id UNIQUE (weld_id, exposure_index)
);

CREATE TABLE indication (
    radiograph_id INTEGER NOT NULL,
    kind CHARACTER VARYING(8) NOT NULL,
    starts_at BIGINT NOT NULL,
    length BIGINT NOT NULL,
    width BIGINT NOT NULL,
    depth_fraction CHARACTER VARYING,
    clock_minutes INTEGER,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_indication_length_not_negative CHECK (length >= 0),
    CONSTRAINT ck_indication_starts_on_the_weld CHECK (starts_at >= 0),
    CONSTRAINT ck_indication_width_not_negative CHECK (width >= 0),
    CONSTRAINT fk_indication_radiograph_id_radiograph FOREIGN KEY (radiograph_id) REFERENCES radiograph (id),
    CONSTRAINT pk_indication PRIMARY KEY (id)
);
