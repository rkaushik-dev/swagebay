-- Device inspections, and the defects raised on them as rows of their own.

CREATE TABLE inspection (
    device_serial CHARACTER VARYING(40) NOT NULL,
    performed_on DATE NOT NULL,
    performed_by CHARACTER VARYING(20) NOT NULL,
    is_quarterly BOOLEAN NOT NULL,
    items_checked CHARACTER VARYING NOT NULL,
    notes CHARACTER VARYING(400) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_inspection_an_inspection_names_the_device CHECK (length(device_serial) > 0),
    CONSTRAINT ck_inspection_an_inspection_checked_something CHECK (length(items_checked) > 0),
    CONSTRAINT ck_inspection_an_inspection_is_signed CHECK (length(performed_by) > 0),
    CONSTRAINT pk_inspection PRIMARY KEY (id)
);
CREATE INDEX ix_inspection_device ON inspection (device_serial, performed_on);

CREATE TABLE defect (
    inspection_id INTEGER NOT NULL,
    item_key CHARACTER VARYING(30) NOT NULL,
    account CHARACTER VARYING(400) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_defect_a_defect_says_what_is_wrong CHECK (length(account) > 0),
    CONSTRAINT fk_defect_inspection_id_inspection FOREIGN KEY (inspection_id) REFERENCES inspection (id),
    CONSTRAINT pk_defect PRIMARY KEY (id)
);
CREATE INDEX ix_defect_inspection_id ON defect (inspection_id);
CREATE INDEX ix_defect_item ON defect (item_key);
