-- The small registers: calibrations, control strips, the film archive, incidents, film lots and
-- welder qualifications. Each is its own table with its own constraints.

CREATE TABLE calibration (
    serial CHARACTER VARYING(40) NOT NULL,
    instrument_kind CHARACTER VARYING(40) NOT NULL,
    calibrated_on DATE NOT NULL,
    due_on DATE NOT NULL,
    laboratory CHARACTER VARYING(120) NOT NULL,
    certificate_reference CHARACTER VARYING(60) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_calibration_expires_after_issue CHECK (due_on > calibrated_on),
    CONSTRAINT pk_calibration PRIMARY KEY (id)
);
CREATE INDEX ix_calibration_serial_due ON calibration (serial, due_on);

CREATE TABLE control_strip (
    processor CHARACTER VARYING(40) NOT NULL,
    read_on DATE NOT NULL,
    speed CHARACTER VARYING NOT NULL,
    contrast CHARACTER VARYING NOT NULL,
    fog CHARACTER VARYING NOT NULL,
    operator CHARACTER VARYING(40) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_control_strip_readings_positive CHECK (speed > 0 AND contrast > 0 AND fog > 0),
    CONSTRAINT pk_control_strip PRIMARY KEY (id),
    CONSTRAINT uq_control_strip_processor UNIQUE (processor, read_on)
);

CREATE TABLE filed (
    radiograph CHARACTER VARYING(40) NOT NULL,
    job CHARACTER VARYING(20) NOT NULL,
    filed_on DATE NOT NULL,
    retention CHARACTER VARYING(40) NOT NULL,
    site CHARACTER VARYING(120),
    cabinet CHARACTER VARYING(40),
    box CHARACTER VARYING(40),
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT pk_filed PRIMARY KEY (id),
    CONSTRAINT uq_filed_radiograph UNIQUE (radiograph)
);
CREATE INDEX ix_filed_job ON filed (job);

CREATE TABLE incident (
    reference CHARACTER VARYING(40) NOT NULL,
    occurrence CHARACTER VARYING(60) NOT NULL,
    discovered_at TIMESTAMP(6) NOT NULL,
    site CHARACTER VARYING(120) NOT NULL,
    reported_by CHARACTER VARYING(40) NOT NULL,
    account CHARACTER VARYING(2000) NOT NULL,
    notified_at TIMESTAMP(6),
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_incident_reported_after_found CHECK (notified_at IS NULL OR notified_at >= discovered_at),
    CONSTRAINT pk_incident PRIMARY KEY (id),
    CONSTRAINT uq_incident_reference UNIQUE (reference)
);
CREATE INDEX ix_incident_discovered_at ON incident (discovered_at);

CREATE TABLE lot (
    lot_number CHARACTER VARYING(40) NOT NULL,
    film_key CHARACTER VARYING(20) NOT NULL,
    size CHARACTER VARYING(20) NOT NULL,
    sheets INTEGER NOT NULL,
    received_on DATE NOT NULL,
    expires_on DATE NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_lot_expires_after_arrival CHECK (expires_on > received_on),
    CONSTRAINT ck_lot_sheets_not_negative CHECK (sheets >= 0),
    CONSTRAINT pk_lot PRIMARY KEY (id),
    CONSTRAINT uq_lot_lot_number UNIQUE (lot_number)
);
CREATE INDEX ix_lot_film_size_expiry ON lot (film_key, size, expires_on);

CREATE TABLE qualification (
    welder CHARACTER VARYING(40) NOT NULL,
    process CHARACTER VARYING(20) NOT NULL,
    position CHARACTER VARYING(10) NOT NULL,
    coupon BIGINT NOT NULL,
    material_group CHARACTER VARYING(20) NOT NULL,
    qualified_on DATE NOT NULL,
    last_used_on DATE NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_qualification_coupon_positive CHECK (coupon > 0),
    CONSTRAINT pk_qualification PRIMARY KEY (id),
    CONSTRAINT uq_qualification_welder UNIQUE (welder, process, qualified_on)
);
CREATE INDEX ix_qualification_welder ON qualification (welder);
