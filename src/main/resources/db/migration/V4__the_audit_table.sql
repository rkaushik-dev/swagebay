-- The audit trail: appended to, never updated. It is indexed on the record an entry describes and
-- on who made it, because the questions asked of it are about one record or one person.

CREATE TABLE audit (
    at TIMESTAMP(6) NOT NULL,
    actor CHARACTER VARYING(20) NOT NULL,
    action CHARACTER VARYING(12) NOT NULL,
    record CHARACTER VARYING(40) NOT NULL,
    identity CHARACTER VARYING(60) NOT NULL,
    field_name CHARACTER VARYING(40) NOT NULL,
    was CHARACTER VARYING NOT NULL,
    became CHARACTER VARYING NOT NULL,
    reason CHARACTER VARYING(200) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_audit_audit_names_an_actor CHECK (length(actor) > 0),
    CONSTRAINT ck_audit_audit_names_a_record CHECK (length(record) > 0),
    CONSTRAINT pk_audit PRIMARY KEY (id)
);
CREATE INDEX ix_audit_actor ON audit (actor, at);
CREATE INDEX ix_audit_record ON audit (record, identity, at);
