-- The non conformance register. A report's reference is unique across the register, its
-- disposition stays empty until somebody decides, and its author cannot close it.

CREATE TABLE nonconformance (
    reference CHARACTER VARYING(40) NOT NULL,
    job CHARACTER VARYING(20) NOT NULL,
    item CHARACTER VARYING(60) NOT NULL,
    requirement CHARACTER VARYING(120) NOT NULL,
    account CHARACTER VARYING NOT NULL,
    raised_on DATE NOT NULL,
    raised_by CHARACTER VARYING(20) NOT NULL,
    disposition CHARACTER VARYING(20),
    concession CHARACTER VARYING(60) NOT NULL,
    removal CHARACTER VARYING(60) NOT NULL,
    closed_on DATE,
    closed_by CHARACTER VARYING(20),
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT ck_nonconformance_a_report_is_not_closed_by_its_author CHECK (closed_by IS NULL OR closed_by <> raised_by),
    CONSTRAINT ck_nonconformance_a_report_closes_after_it_opens CHECK (closed_on IS NULL OR closed_on >= raised_on),
    CONSTRAINT ck_nonconformance_a_closed_report_has_been_decided CHECK (closed_on IS NULL OR disposition IS NOT NULL),
    CONSTRAINT ck_nonconformance_a_report_is_raised_by_somebody CHECK (length(raised_by) > 0),
    CONSTRAINT ck_nonconformance_a_report_has_a_reference CHECK (length(reference) > 0),
    CONSTRAINT pk_nonconformance PRIMARY KEY (id),
    CONSTRAINT uq_nonconformance_reference UNIQUE (reference)
);
CREATE INDEX ix_nonconformance_job ON nonconformance (job, raised_on);
CREATE INDEX ix_nonconformance_open ON nonconformance (closed_on);
